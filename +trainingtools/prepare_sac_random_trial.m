function info=prepare_sac_random_trial(device,workers,trainingSeed)
% Prepare only. GPU + six process workers by default; no pool or training.
if nargin<1,device='gpu';end
if nargin<2,workers=6;end
if nargin<3,trainingSeed=28001;end
validateattributes(trainingSeed,{'numeric'},{'scalar','integer','>=',0,'<=',1e9});
validateattributes(workers,{'numeric'},{'scalar','integer','positive'});
root=fileparts(fileparts(mfilename('fullpath')));
info=retry(curriculum=fullfile(root,'experiments','sac_random_route_v1','curriculum.json'), ...
    environment='spatial_v2',executionMode='parallel',device=device, ...
    workers=workers,minWorkers=workers,fallbackWorkers=[],fastRestart='off', ...
    episodesPerProcess=500,checkpointEvery=100,averageWindow=100, ...
    maxAttempts=1,maxNoProgressFailures=1,start=false);
rules=jsondecode(fileread(fullfile(root,'configs','recovery_actor_half.json')));
rules=rules.guard;rules.origin_episode=0;rules.max_additional_episodes=20000;
rules.budget_enabled=true;rules.regression_action='pause';
trainingcurriculum.write_json(fullfile(info.sessionDir,'training_guard.json'),rules);
trainingcurriculum.write_json(fullfile(info.sessionDir,'checkpoint_storage.json'),struct('schema_version',1,'version','-v7'));
protocol=struct('schema_version',1,'kind','paper_inspired_random_route', ...
    'training_seed',trainingSeed, ...
    'initialization','fresh agent/replay/optimizer; same agent and replay across stages', ...
    'learning_rate','constant3e-4 from paper altitude setting; not attitude linear schedule', ...
    'route_generator','existing spatial random generator; seed recorded per worker episode', ...
    'evaluation','paused CPU frozen evaluation; no automatic simulation launch', ...
    'first_attempt_episodes',500,'episode_cap',20000,'step_upper_bound',60000000, ...
    'scope','new task/recipe feasibility trial, not a causal ablation or paper reproduction');
trainingcurriculum.write_json(fullfile(info.sessionDir,'experiment_protocol.json'),protocol);
fprintf('Prepared %s. No training started. Save the returned path as a receipt.\n',info.sessionDir);
end
