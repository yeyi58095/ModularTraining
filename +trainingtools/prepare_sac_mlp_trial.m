function info=prepare_sac_mlp_trial()
% Prepare an independent fresh Stage1-only pilot. Never start training here.
root=fileparts(fileparts(mfilename('fullpath')));
info=retry(curriculum=fullfile(root,'experiments','sac_mlp_stage1_v1','curriculum.json'), ...
    environment='spatial_v2',executionMode='serial',device='cpu', ...
    workers=1,minWorkers=1,fallbackWorkers=[],fastRestart='off', ...
    episodesPerProcess=500,checkpointEvery=100,averageWindow=100, ...
    maxAttempts=1,maxNoProgressFailures=1,start=false);
rules=jsondecode(fileread(fullfile(root,'configs','recovery_actor_half.json')));
rules=rules.guard;rules.origin_episode=0;rules.max_additional_episodes=2000;
trainingcurriculum.write_json(fullfile(info.sessionDir,'training_guard.json'),rules);
protocol=struct('schema_version',1,'kind','fresh_architecture_pilot', ...
    'initialization','new weights, empty replay, new optimizer; no parent checkpoint', ...
    'hypothesis','Test feedforward SAC without recurrent state and sequence replay.', ...
    'review_episodes',[500 1000 1500 2000],'review_automatic',false, ...
    'first_launch_episode_cap',500,'total_episode_cap',2000, ...
    'evaluation','Frozen Stage1 policy, exploration off/on, survival and finite-route distance.', ...
    'scope','Stage1-only pilot; not eight-stage completion or proof of LSTM root cause');
trainingcurriculum.write_json(fullfile(info.sessionDir,'experiment_protocol.json'),protocol);
fprintf('Prepared fresh MLP SAC. One500-episode attempt; Stage1-only total budget2000.\n');
end
