function manifest=verify(manifestFile,assetDir)
% Verify a flat, explicitly enumerated environment bundle. No path guessing.
manifest=jsondecode(fileread(manifestFile));
assert(isstruct(manifest) && isscalar(manifest) && isfield(manifest,'schema_version') && ...
    isequal(manifest.schema_version,1) && all(isfield(manifest,{'id','model_file','files'})), ...
    'Environment:Manifest','Invalid environment manifest.');
assert(ischar(manifest.id) && ~isempty(regexp(manifest.id,'^[a-z][a-z0-9_]*$','once')), ...
    'Environment:Manifest','Invalid environment id.');
assert(strcmp(manifest.model_file,'FAFA_Simulation.slx'), ...
    'Environment:Interface','This engine requires FAFA_Simulation.slx.');
files=manifest.files;if iscell(files),files=[files{:}];end
assert(isstruct(files) && ~isempty(files) && all(isfield(files,{'name','sha256'})), ...
    'Environment:Manifest','Missing file list.');
names=strings(0);
for i=1:numel(files)
    name=files(i).name;
    assert(ischar(name) && ~isempty(regexp(name,'^[^/\\:]+\.(slx|mat|m|sldd)$','once')) && ...
        ~startsWith(name,'.') && ~endsWith(name,' ') && ...
        isempty(regexpi(name,'^(Agent.*\.mat|checkpoint_.*\.m|training_engine\.m|retry\.m)$','once')) && ...
        ~any(strcmpi(names,name)), 'Environment:Path','Invalid or duplicate bundle filename.');
    names(end+1)=string(name); %#ok<AGROW>
    assert(ischar(files(i).sha256) && ~isempty(regexp(files(i).sha256,'^[a-fA-F0-9]{64}$','once')), ...
        'Environment:Manifest','Invalid SHA256.');
    file=fullfile(assetDir,name);
    assert(isfile(file) && strcmpi(checkpointreview.sha256(file),files(i).sha256), ...
        'Environment:HashMismatch','Missing or changed environment file: %s',file);
end
assert(any(names==string(manifest.model_file)),'Environment:Manifest','Model absent from bundle.');
manifest.files=files;
end
