function manifest=build_spatial_v2()
% Authoring tool: build a NEW bundle from the pinned v1 model. Never overwrite.
root=fileparts(fileparts(mfilename('fullpath')));addpath(root);
[sourceManifest,sourceDir]=trainingenv.registry(root,'spatial_v1');
source=trainingenv.verify(sourceManifest,sourceDir);
target=fullfile(root,'environments','spatial_v2');
assert(~isfolder(target),'Environment:Exists','spatial_v2 already exists; refusing overwrite.');
assert(~bdIsLoaded('FAFA_Simulation'),'Environment:AlreadyLoaded','Close FAFA_Simulation first.');
sourceModel=fullfile(sourceDir,source.model_file);before=checkpointreview.sha256(sourceModel);
oldFolder=pwd;oldPath=path;
restore=onCleanup(@()restoreCaller(oldFolder,oldPath)); %#ok<NASGU>
cd(sourceDir);load_system(sourceModel);
closeGuard=onCleanup(@()close_system('FAFA_Simulation',0)); %#ok<NASGU>
c13=find(sfroot,'-isa','Stateflow.EMChart','Path','FAFA_Simulation/OBSERVATION/MATLAB Function13');
c22=find(sfroot,'-isa','Stateflow.EMChart','Path','FAFA_Simulation/OBSERVATION/MATLAB Function22');
assert(isscalar(c13) && isscalar(c22),'Environment:RewardChart','Expected reward charts.');
assert(contains(c13.Script,'0.5 *d') && contains(c22.Script,'dis <= 150'), ...
    'Environment:RewardDrift','Unexpected baseline reward implementation.');
assert(str2double(get_param('FAFA_Simulation/OBSERVATION/Gain9','Gain'))==0.2 && ...
    str2double(get_param('FAFA_Simulation/OBSERVATION/Gain11','Gain'))==0.1, ...
    'Environment:RewardDrift','Unexpected reward gains.');
c13.Script=sprintf(['function y = fcn(kt, d)\n' ...
    '%% SPATIAL_REWARD_V2: d is guidance distance / 30.\n' ...
    '%% Keep the existing ports; remove curvature-dependent penalty relief.\n' ...
    '%% Downstream reward is 0.2 * (1 - abs(y)).\n' ...
    '%%#codegen\n' ...
    'y = d;\nend\n']);
c22.Script=sprintf(['function y = fcn(d, dis)\n' ...
    '%% SPATIAL_REWARD_V2: restore physical metres before applying 10 m bonus.\n' ...
    '%% dis is retained as an unused interface input; no waypoint-distance bonus.\n' ...
    '%% Downstream reward is 0.1 * (1 + y), including the explicit baseline.\n' ...
    '%%#codegen\n' ...
    'd_m = 30 * abs(d);\n' ...
    'y = 0.5 * max(0, 1 - d_m / 10);\nend\n']);
mkdir(target);
save_system('FAFA_Simulation',fullfile(target,'FAFA_Simulation.slx'));
assert(strcmp(before,checkpointreview.sha256(sourceModel)),'Environment:SourceChanged','v1 changed.');
manifest=struct('schema_version',1,'id','spatial_v2','model_file','FAFA_Simulation.slx', ...
    'reward_version','spatial_reward_v2','parent_environment','spatial_v1', ...
    'parent_model_sha256',before,'distance_weight',0.2,'distance_scale_m',30, ...
    'close_bonus_radius_m',10,'validation_status','Formula and frozen-policy validation; training convergence unverified', ...
    'provenance','Only OBSERVATION MATLAB Function13 and Function22 reward logic changed.', ...
    'files',struct('name','FAFA_Simulation.slx','sha256', ...
    checkpointreview.sha256(fullfile(target,'FAFA_Simulation.slx'))));
trainingcurriculum.write_json(fullfile(target,'environment.json'),manifest);
trainingenv.verify(fullfile(target,'environment.json'),target);
fprintf('Created spatial_v2. v1 and runtime unchanged. No training started.\n');
end
function restoreCaller(folder,p)
cd(folder);path(p);
end
