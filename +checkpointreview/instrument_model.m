function signals=instrument_model(mdl)
% 評估訊號記錄：在未保存的評估模型副本啟用位置、window／planner 路徑與 guidance 目標記錄。
% 回傳 signals 清單；只改 logging，不改 chart 程式或正式 runtime SLX。
% Add only signal logging to an unsaved evaluation copy. No chart edits.
spec={ ...
    'P_E', 'OBSERVATION/P_E',1; ...
    'P_N', 'OBSERVATION/P_N',1; ...
    'psi', 'OBSERVATION/psi',1; ...
    'phi', 'OBSERVATION/phi',1; ...
    'planned_path','OBSERVATION/MATLAB Function8',1; ...
    'window_path','OBSERVATION/MATLAB Function3',1; ...
    'window_valid','OBSERVATION/MATLAB Function3',3; ...
    'loiter','OBSERVATION/MATLAB Function3',4; ...
    'distance_to_window_target','OBSERVATION/MATLAB Function3',5; ...
    'target_E','OBSERVATION/MATLAB Function12',1; ...
    'target_N','OBSERVATION/MATLAB Function12',2; ...
    'guidance_d','OBSERVATION/MATLAB Function12',3; ...
    'guidance_delta_psi','OBSERVATION/MATLAB Function12',4; ...
    'guidance_heta','OBSERVATION/MATLAB Function12',5};
signals=struct('name',{},'block',{},'port',{});
set_param(mdl,'SignalLogging','on','SignalLoggingName','review_signals');
for k=1:size(spec,1)
    block=[mdl '/' spec{k,2}];
    handles=get_param(block,'PortHandles');
    port=handles.Outport(spec{k,3});
    set_param(port,'DataLogging','on','DataLoggingNameMode','Custom', ...
        'DataLoggingName',spec{k,1},'DataLoggingDecimateData','off', ...
        'DataLoggingLimitDataPoints','off');
    signals(k)=struct('name',spec{k,1},'block',spec{k,2},'port',spec{k,3});
end
end
