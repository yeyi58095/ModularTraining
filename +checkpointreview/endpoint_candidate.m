function script=endpoint_candidate(script)
% Experimental geometry-only change; caller must use an evaluation copy.
marker='        % Compute heading difference';
locations=strfind(script,marker);
assert(numel(locations)==2 && contains(script,'function [E, N, d, delta_psi, heta, curvature] = guidance_law'), ...
    'Evaluation:GuidanceDrift','Unexpected guidance implementation; review candidate before use.');
code=strjoin({ ...
    '        % Evaluation candidate: extend terminal lookahead while waiting for a new path.'; ...
    '        % Only the inside-window branch and its endpoint target are affected.'; ...
    '        if k == numWps'; ...
    '            tail = path(numWps,1:2) - path(numWps-1,1:2);'; ...
    '            tail_length = norm(tail);'; ...
    '            if tail_length > 1e-6'; ...
    '                tangent = tail / tail_length;'; ...
    '                along = dot([P_E, P_N] - path(numWps,1:2), tangent);'; ...
    '                extension = max(0, target_distance + along);'; ...
    '                E = path(numWps,1) + extension*tangent(1);'; ...
    '                N = path(numWps,2) + extension*tangent(2);'; ...
    '            end'; ...
    '        end'; ...
    ''},newline);
p=locations(1); script=[script(1:p-1) code newline script(p:end)];
end
