function script=endpoint_candidate(script,includeOutside)
% 候選 guidance 文字轉換：在舊版評估副本補足末段 lookahead，選用 V2 的受限 outside 延伸。
% 輸入／回傳 chart script；正式 runtime 已有修正時拒絕重複套用，不直接修改正式 SLX。
% Experimental geometry-only change; caller must use an evaluation copy.
if nargin<2, includeOutside=false; end
assert(~contains(script,'extension = max(0, target_distance + along);'), ...
    'Evaluation:AlreadyApplied', ...
    'Endpoint lookahead is already in the source model. Use guidanceVariant="baseline" to evaluate the current runtime.');
marker='        % Compute heading difference';
locations=strfind(script,marker);
assert(numel(locations)==2 && contains(script,'function [E, N, d, delta_psi, heta, curvature] = guidance_law'), ...
    'Evaluation:GuidanceDrift','Unexpected guidance implementation; review candidate before use.');
code=strjoin({ ...
    '        % Evaluation candidate: extend terminal lookahead while waiting for a new path.'; ...
    '        % Only the inside-window branch and its endpoint target are affected.'; ...
    '        if k == numWps'; ...
    '            tail = path(numWps,1:2) - path(numWps-1,1:2);'; ...
    '            tail_length = norm(tail);'; ...
    '            if tail_length > 1e-6'; ...
    '                tangent = tail / tail_length;'; ...
    '                along = dot([P_E, P_N] - path(numWps,1:2), tangent);'; ...
    '                extension = max(0, target_distance + along);'; ...
    '                E = path(numWps,1) + extension*tangent(1);'; ...
    '                N = path(numWps,2) + extension*tangent(2);'; ...
    '            end'; ...
    '        end'; ...
    ''},newline);
p=locations(1); script=[script(1:p-1) code newline script(p:end)];
if includeOutside
    code=strjoin({ ...
        '        % V2: only handle longitudinal overshoot near the terminal ray.'; ...
        '        tail = path(numWps,1:2) - path(numWps-1,1:2);'; ...
        '        tail_length = norm(tail);'; ...
        '        if tail_length > 1e-6'; ...
        '            tangent = tail / tail_length;'; ...
        '            offset = [P_E, P_N] - path(numWps,1:2);'; ...
        '            along = dot(offset, tangent);'; ...
        '            lateral = norm(offset - along*tangent);'; ...
        '            [~, nearest_terminal] = min(point_dists);'; ...
        '            if nearest_terminal == numWps && along >= 0 && lateral <= margin'; ...
        '                E = path(numWps,1) + (along + 50)*tangent(1);'; ...
        '                N = path(numWps,2) + (along + 50)*tangent(2);'; ...
        '            end'; ...
        '        end'; ...
        ''},newline);
    locations=strfind(script,marker); p=locations(2);
    script=[script(1:p-1) code newline script(p:end)];
end
end
