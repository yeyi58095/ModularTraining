function summary=aggregate(results)
summary={};
for i=1:numel(results)
    first=results{i};
    if any(cellfun(@(r) r.checkpoint_episode==first.checkpoint_episode && ...
            strcmp(r.stage_id,first.stage_id),summary)), continue; end
    selected=cellfun(@(r) r.checkpoint_episode==first.checkpoint_episode && ...
        strcmp(r.stage_id,first.stage_id),results);
    rows=[results{selected}];
    [~,worst]=min([rows.reward]);
    summary{end+1}=struct('checkpoint_episode',first.checkpoint_episode, ...
        'stage_id',first.stage_id,'count',numel(rows), ...
        'step_limit_rate',mean([rows.reached_step_limit] & ~[rows.environment_done]), ...
        'mean_reward',mean([rows.reward]),'mean_steps',mean([rows.steps]), ...
        'mean_observation7_rms',mean([rows.observation7_rms]), ...
        'worst_reward_seed',rows(worst).seed,'worst_reward_trace',rows(worst).trace); %#ok<AGROW>
end
end
